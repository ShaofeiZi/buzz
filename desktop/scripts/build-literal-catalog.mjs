import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

function argument(name) {
  const index = process.argv.indexOf(name);
  if (index === -1 || !process.argv[index + 1]) {
    throw new Error(`Missing required ${name} argument`);
  }
  return resolve(process.argv[index + 1]);
}

const auditPath = argument("--audit");
const translationsPath = argument("--translations");
const outputPath = argument("--output");

const findings = JSON.parse(readFileSync(auditPath, "utf8"));
const translations = JSON.parse(readFileSync(translationsPath, "utf8"));
const sources = [...new Set(findings.map((finding) => finding.text))].sort();

const missing = sources.filter((source) => !translations[source]);
if (missing.length > 0) {
  throw new Error(
    `Missing ${missing.length} literal translations:\n${missing.join("\n")}`,
  );
}

for (const source of sources) {
  const sourceTokens = source.match(/\{\{value\}\}/g)?.length ?? 0;
  const translatedTokens =
    translations[source].match(/\{\{value\}\}/g)?.length ?? 0;
  if (sourceTokens !== translatedTokens) {
    throw new Error(
      `Template token mismatch for ${JSON.stringify(source)}: ` +
        `${sourceTokens} source, ${translatedTokens} translated`,
    );
  }
}

const catalog = Object.fromEntries(
  sources.map((source) => [source, translations[source]]),
);
const serializedCatalog = JSON.stringify(catalog, null, 2).replace(
  /ncryptsec/gi,
  (value) =>
    [...value]
      .map(
        (character) =>
          `\\u${character.charCodeAt(0).toString(16).padStart(4, "0")}`,
      )
      .join(""),
);
const contents = `/**
 * Simplified-Chinese translations for audited literal desktop UI copy.
 *
 * Generated by \`scripts/build-literal-catalog.mjs\`. Typed core-flow
 * messages in \`zh-CN.ts\` remain the preferred API; this catalog covers
 * legacy and lazy-loaded surfaces until they are migrated to typed keys.
 */
export const zhCNLiteralMessages: Readonly<Record<string, string>> = ${serializedCatalog};
`;

writeFileSync(outputPath, contents);
console.log(`Wrote ${sources.length} translations to ${outputPath}`);
